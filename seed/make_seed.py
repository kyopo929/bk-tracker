"""Builds supabase/seed.sql from the SharePoint exports in seed/source/.

Rules used for the move (decided 24 Nov 2026):
- Old/new pairs and duplicates from the pairing sheet become one part with several numbers.
  For old->new pairs the new number is the main one.
- Where lists disagree, Order Line Items wins: its "Qty Shipped" is the truth. Shipments recorded
  in the Shipments list are loaded as delivery lines; whatever the line says was shipped beyond
  that is "shipped before tracking".
- A shipment with no matching order line gets a line created for it (noted on the line).
Run: python3 seed/make_seed.py
"""
import csv, pathlib, uuid, urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / 'source'
NS = uuid.UUID('6f1c2a3e-1b2c-4d5e-8f90-0a1b2c3d4e5f')
def uid(*k): return str(uuid.uuid5(NS, '|'.join(map(str, k))))

def tsv(name):
    lines = [l for l in (SRC / name).read_text(encoding='utf-8').splitlines() if l and not l.startswith('#')]
    return [{k: (v or '') for k, v in r.items()} for r in csv.DictReader(lines, delimiter='\t')]

def q(v):
    if v is None or v == '': return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(v) if not float(v).is_integer() else str(int(v))
    return "'" + str(v).replace("'", "''") + "'"

def num(s): return float(str(s).replace(',', '')) if s not in (None, '') else 0.0

# ---- parts ----
raw_parts = [l.split('\t', 1) for l in (SRC / 'parts.tsv').read_text(encoding='utf-8').splitlines() if l]
desc = {n.strip(): d.strip() for n, d in raw_parts}
pairs = tsv('pairs.tsv')
alias_of = {}          # alias number -> main number
labels = {}
for p in pairs:
    alias_of[p['alias']] = p['main']
    if p['kind'] == 'pair':
        labels[p['main']] = 'new'; labels[p['alias']] = 'old'
part_of_number = {}    # number -> part id
out = []
w = out.append
w('-- BK Tracker: data moved from SharePoint (UAEWETCareOps lists), 24 Nov 2026.')
w('-- Generated by seed/make_seed.py. Run once, after schema.sql. Running it again does nothing.')
w('begin;')
w("do $$ begin if exists (select 1 from public.orders) then raise exception 'Data is already loaded: nothing was changed.'; end if; end $$;")
w('')
w('-- Parts')
parts_rows, number_rows = [], []
for n, d in raw_parts:
    n = n.strip()
    if n in alias_of: continue
    pid = uid('part', n)
    notes = []
    for a, m in alias_of.items():
        if m == n and desc.get(a, '').lower() != d.strip().lower():
            notes.append(f'{a} was listed as: {desc.get(a)}')
    parts_rows.append(f"({q(pid)}, {q(d.strip())}, {q(chr(10).join(notes) or None)})")
    number_rows.append(f"({q(uid('num', n))}, {q(pid)}, {q(n)}, {q(labels.get(n))}, true)")
    part_of_number[n] = pid
for a, m in alias_of.items():
    pid = part_of_number[m]
    number_rows.append(f"({q(uid('num', a))}, {q(pid)}, {q(a)}, {q(labels.get(a))}, false)")
    part_of_number[a] = pid
w('insert into public.parts (id, description, notes) values\n  ' + ',\n  '.join(parts_rows) + ';')
w('insert into public.part_numbers (id, part_id, number, label, is_main) values\n  ' + ',\n  '.join(number_rows) + ';')

# ---- orders ----
orders = tsv('orders.tsv')
order_id = {o['po_number']: uid('order', o['po_number']) for o in orders}
w('\n-- Orders')
rows = []
for o in orders:
    rows.append(f"({q(order_id[o['po_number']])}, {q(o['title'].strip())}, {q(o['client'])}, {q(o['quote_sent'])}, {q(o['po_number'])}, {q(o['po_date'])}, {q(o['notes'].strip() or None)})")
w('insert into public.orders (id, title, client, quote_sent, po_number, po_date, notes) values\n  ' + ',\n  '.join(rows) + ';')

# ---- lines + shipment allocation ----
lines = tsv('lines.tsv')
for i, l in enumerate(lines):
    l['id'] = uid('line', i, l['po'], l['part'])
    l['part_id'] = part_of_number[l['part']]
    l['qty'] = num(l['qty']); l['shipped'] = num(l['shipped']); l['allocated'] = 0.0; l['note'] = None
ships = tsv('shipments.tsv')
for s in ships:
    s['qty'] = num(s['qty']); pid = part_of_number[s['part']]
    cands = [l for l in lines if l['po'] == s['po'] and l['part_id'] == pid]
    cands.sort(key=lambda l: (l['shipped'] - l['allocated'] < s['qty'], -(l['shipped'] - l['allocated'])))
    if cands and cands[0]['shipped'] - cands[0]['allocated'] > 0:
        line = cands[0]
    else:
        line = {'id': uid('line-added', s['po'], s['part']), 'po': s['po'], 'part': s['part'], 'part_id': pid,
                'qty': s['qty'], 'shipped': s['qty'], 'allocated': 0.0, 'urgent': '',
                'note': 'Added during the move: SharePoint had a shipment for this but no order line.'}
        lines.append(line)
    take = s['qty']
    line['allocated'] += take
    s['line_id'] = line['id']; s['part_id'] = pid
w('\n-- Order lines')
rows = []
for i, l in enumerate(lines):
    before = max(0.0, l['shipped'] - l['allocated'])
    rows.append(f"({q(l['id'])}, {q(order_id[l['po']])}, {q(l['part_id'])}, {q(l['part'])}, {q(l['qty'])}, {q(before)}, {q(l['urgent'] == 'Urgent')}, {q(l['note'])}, {i})")
w('insert into public.order_lines (id, order_id, part_id, ordered_as, qty, shipped_before, urgent, notes, sort) values\n  ' + ',\n  '.join(rows) + ';')

# ---- deliveries ----
dels = tsv('deliveries.tsv')
del_id = {d['dn']: uid('dn', d['dn']) for d in dels}
w('\n-- Deliveries')
rows = [f"({q(del_id[d['dn']])}, {q(d['dn'])}, {q(order_id[d['po']])}, {q(d['ship_date'])}, {q(d['tracking'])}, {q(d['notes'])})" for d in dels]
w('insert into public.deliveries (id, dn_number, order_id, ship_date, tracking, notes) values\n  ' + ',\n  '.join(rows) + ';')
rows = [f"({q(uid('dl', i, s['dn'], s['part']))}, {q(del_id[s['dn']])}, {q(s['line_id'])}, {q(s['part_id'])}, {q(s['part'])}, {q(s['qty'])}, {q(s['notes'] or None)})" for i, s in enumerate(ships)]
w('insert into public.delivery_lines (id, delivery_id, order_line_id, part_id, shipped_as, qty, notes) values\n  ' + ',\n  '.join(rows) + ';')

# ---- problems found on delivery (from the delivery note notes) ----
def line_for(po, number):
    pid = part_of_number[number]
    return next(l['id'] for l in lines if l['po'] == po and l['part_id'] == pid and l['qty'] > l['shipped'])
issues = [
    ('SO32320', 'PO5002393', '8481', 'Wrong item', 12, '12 pcs Swivel Cut Plate received instead of 09110 Nozzle, Base, Delrin.'),
    ('SO32318', 'PO5002012', '8482', 'Short', 50, '09100 Piston, Nozzle, MicroShooter: all 50 pcs missing.'),
    ('SO32318', 'PO5002012', '8481', 'Wrong item', 88, '88 pcs Swivel Cut Plate received instead of 09110 Nozzle, Base, Delrin.'),
]
w('\n-- Problems noted on delivery notes (all still open)')
rows = [f"({q(uid('issue', i))}, {q(del_id[dn])}, {q(line_for(po, n))}, {q(k)}, {q(qty)}, {q(t)})" for i, (dn, po, n, k, qty, t) in enumerate(issues)]
w('insert into public.issues (id, delivery_id, order_line_id, kind, qty, description) values\n  ' + ',\n  '.join(rows) + ';')

# ---- documents ----
base = 'https://wetdesign.sharepoint.com/sites/UAEWETCareOps/7%20Order%20Documents/'
docs = tsv('documents.tsv')
w('\n-- Documents (files stay in SharePoint; these are links)')
rows = [f"({q(uid('doc', d['name']))}, {q(d['name'])}, {q(base + urllib.parse.quote(d['name']))}, {q(d['doc_type'])}, {q(order_id[d['po']])}, {q(del_id.get(d['dn']) if d['dn'] else None)})" for d in docs]
w('insert into public.documents (id, name, url, doc_type, order_id, delivery_id) values\n  ' + ',\n  '.join(rows) + ';')
w('\ncommit;')

(ROOT.parent / 'supabase' / 'seed.sql').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('parts', len(parts_rows), 'numbers', len(number_rows), 'orders', len(orders), 'lines', len(lines), 'deliveries', len(dels), 'delivery lines', len(ships), 'docs', len(docs))
for l in lines:
    if l['allocated'] > l['shipped'] and l.get('note') is None:
        print('WARN over-allocated', l['po'], l['part'], l['allocated'], l['shipped'])
